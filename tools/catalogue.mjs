/** Generate reviewable catalogue documentation from the actual runtime data. */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT } from './build.mjs';
import { BUILTIN_SCALES } from '../src/catalog/scales.js';
import { PRESETS } from '../src/catalog/presets.js';
import { THEMES, DENSITIES } from '../src/catalog/appearance.js';
import { DEFAULT_STATE } from '../src/catalog/defaults.js';
const clean = value => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const json = value => JSON.stringify(value, null, 2) + '\n';
const directory = join(ROOT, 'docs/data');
await mkdir(directory, { recursive: true });
for (const [name, data] of Object.entries({ scales: BUILTIN_SCALES, presets: PRESETS, themes: THEMES, densities: DENSITIES, defaults: DEFAULT_STATE })) {
    await writeFile(join(directory, name + '.json'), json(data));
}
const lines = [
    '# Generated catalogue', '',
    'Generated by `node tools/catalogue.mjs` from source data. Edit source, not this file.', '',
    '## Presets', '',
    '| ID | Instrument / purpose | Faces |', '| --- | --- | --- |'
];
for (const [id, preset] of Object.entries(PRESETS)) {
    lines.push(`| \`${id}\` | ${clean(preset.modelLabel || preset.name || preset.label)} | ${Object.keys(preset.sides).map(clean).join(', ')} |`);
}
lines.push('', '## Scale definitions', '', 'Aliases and composites are counted as definitions, not distinct mathematical functions.', '', '| ID | Printed name | Type | Family | Meaning |', '| --- | --- | --- | --- | --- |');
for (const [id, scale] of Object.entries(BUILTIN_SCALES)) {
    lines.push(`| \`${id}\` | ${clean(scale.label)} | ${clean(scale.type)} | ${clean(scale.family)} | ${clean(scale.description || scale.formula)} |`);
}
lines.push('', 'Machine-readable copies are in `docs/data/`. Semantic validation remains in `src/model/validation.js`.', '');
await writeFile(join(ROOT, 'docs/CATALOGUE.md'), lines.join('\n'));
console.log(`Exported ${Object.keys(PRESETS).length} presets and ${Object.keys(BUILTIN_SCALES).length} scale definitions.`);
